import { Command } from 'commander';

const GLOBAL_FLAGS = ['--json', '--no-input', '--force', '--help', '--version'];

const STATUSES = ['open', 'in_progress', 'done', 'closed', 'blocked', 'backlogged'];
const PRIORITIES = ['low', 'medium', 'high', 'urgent'];

/**
 * Extract subcommand names + descriptions from a Commander program.
 *
 * This is the single source of truth for the completion command list — it reads
 * directly from the same `program` instance that `bin/tasks.ts` registers
 * commands on, so new commands automatically appear in shell completions
 * without a parallel hardcoded list to maintain.
 *
 * Filters out Commander's built-in `help` subcommand because it isn't a real
 * user-facing command.
 */
function getCommandSpecs(program: Command): Array<{ name: string; description: string }> {
  return program.commands
    .filter((cmd) => cmd.name() !== 'help')
    .map((cmd) => ({
      name: cmd.name(),
      description: cmd.description() || `${cmd.name()} command`,
    }));
}

/** The long flags a Commander command declares itself (e.g. `--status`). */
function longFlagsOf(cmd: Command): string[] {
  return cmd.options.map((opt) => opt.long).filter((long): long is string => Boolean(long));
}

/**
 * The global flags: the fixed set plus every option registered on the root
 * program (so a new global such as `--token` is offered without editing a
 * list here).
 */
function globalFlagsOf(program: Command): string[] {
  return [...new Set([...GLOBAL_FLAGS, ...longFlagsOf(program)])];
}

/** Root-program flags that take a value, so the command scan skips that value. */
function globalValueFlagsOf(program: Command): string[] {
  return program.options
    .filter((opt) => opt.required || opt.optional)
    .map((opt) => opt.long)
    .filter((long): long is string => Boolean(long));
}

/**
 * One bash `case` arm per command with options, setting `cmd_flags` to the
 * long flags that command accepts (WFT #2551). Read from each command's own
 * Commander options, like the command list itself.
 */
function bashCommandFlagCases(program: Command): string {
  return program.commands
    .filter((cmd) => cmd.name() !== 'help')
    .map((cmd) => ({ name: cmd.name(), flags: longFlagsOf(cmd) }))
    .filter((entry) => entry.flags.length > 0)
    .map((entry) => `      ${entry.name}) cmd_flags="${entry.flags.join(' ')}" ;;`)
    .join('\n');
}

function generateBashScript(program: Command): string {
  const specs = getCommandSpecs(program);
  const commandNames = specs.map((s) => s.name);
  const globalValueFlags = globalValueFlagsOf(program);
  return `# bash completion for tasks CLI
# Generated by: tasks completions bash
# Install: tasks completions bash >> ~/.bashrc
#   or:    tasks completions bash > /etc/bash_completion.d/tasks

_tasks_completions() {
  local cur prev commands global_flags statuses priorities cmd cmd_flags i
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"

  commands="${commandNames.join(' ')}"
  global_flags="${globalFlagsOf(program).join(' ')}"
  statuses="${STATUSES.join(' ')}"
  priorities="${PRIORITIES.join(' ')}"

  # The command is the first word after 'tasks' that is not a flag (or the
  # value of a global flag that takes one).
  cmd=""
  i=1
  while (( i < COMP_CWORD )); do
    case "\${COMP_WORDS[i]}" in${globalValueFlags.length > 0 ? `\n      ${globalValueFlags.join('|')}) i=$(( i + 2 )); continue ;;` : ''}
      -*) ;;
      *) cmd="\${COMP_WORDS[i]}"; break ;;
    esac
    i=$(( i + 1 ))
  done

  # The flags this command accepts (WFT #2551).
  cmd_flags=""
  case "\${cmd}" in
${bashCommandFlagCases(program)}
      *) ;;
  esac

  # Complete --status values
  if [[ "\${prev}" == "--status" ]]; then
    COMPREPLY=( $(compgen -W "\${statuses}" -- "\${cur}") )
    return 0
  fi

  # Complete --priority values
  if [[ "\${prev}" == "--priority" ]]; then
    COMPREPLY=( $(compgen -W "\${priorities}" -- "\${cur}") )
    return 0
  fi

  # Complete shell names for completions command
  if [[ "\${prev}" == "completions" ]]; then
    COMPREPLY=( $(compgen -W "bash zsh" -- "\${cur}") )
    return 0
  fi

  # Complete flags: the global ones plus the command's own
  if [[ "\${cur}" == -* ]]; then
    COMPREPLY=( $(compgen -W "\${global_flags} \${cmd_flags}" -- "\${cur}") )
    return 0
  fi

  # Complete commands (the first word that is not a flag)
  if [[ -z "\${cmd}" ]]; then
    COMPREPLY=( $(compgen -W "\${commands}" -- "\${cur}") )
    return 0
  fi
  return 0
}

complete -F _tasks_completions tasks
`;
}

function generateZshScript(program: Command): string {
  const specs = getCommandSpecs(program);
  return `#compdef tasks
# zsh completion for tasks CLI
# Generated by: tasks completions zsh
# Install: tasks completions zsh > ~/.zsh/completions/_tasks
#   then add to .zshrc: fpath=(~/.zsh/completions $fpath)

_tasks() {
  local -a commands statuses priorities global_flags

  commands=(
    ${specs.map((s) => `'${s.name}:${s.name} command'`).join('\n    ')}
  )

  statuses=(${STATUSES.join(' ')})
  priorities=(${PRIORITIES.join(' ')})
  global_flags=(
    '--json[Output as JSON]'
    '--no-input[Disable interactive prompts]'
    '--force[Skip confirmation prompts]'
    '--help[Show help]'
    '--version[Show version]'
  )

  _arguments -C \\
    '1:command:->command' \\
    '*::arg:->args'

  case $state in
    command)
      _describe 'command' commands
      ;;
    args)
      case $words[1] in
        list)
          _arguments \\
            '--status[Filter by status]:status:(${STATUSES.join(' ')})' \\
            '--priority[Filter by priority]:priority:(${PRIORITIES.join(' ')})' \\
            '--assignee[Filter by assignee]:assignee:' \\
            '--tags[Filter by tags]:tags:' \\
            '--search[Search text]:search:' \\
            '--include-archived[Also list tasks of archived projects]' \\
            '--archived-only[List only tasks of archived projects]' \\
            $global_flags
          ;;
        project-list)
          _arguments \\
            '--include-archived[Also list archived projects]' \\
            '--archived-only[List only archived projects]' \\
            '--limit[Max rows]:limit:' \\
            '--offset[Offset]:offset:' \\
            $global_flags
          ;;
        project-archive)
          _arguments \\
            '--reason[Why the project is archived]:reason:' \\
            '--with-unfinished[Archive although tasks are unfinished (requires --reason)]' \\
            $global_flags
          ;;
        create|subtask-create)
          _arguments \\
            '--title[Task title]:title:' \\
            '--status[Task status]:status:(${STATUSES.join(' ')})' \\
            '--priority[Task priority]:priority:(${PRIORITIES.join(' ')})' \\
            '--project[Project ID]:project:' \\
            '--assignee[Assignee]:assignee:' \\
            '--description[Description]:description:' \\
            $global_flags
          ;;
        update)
          _arguments \\
            '--status[New status]:status:(${STATUSES.join(' ')})' \\
            '--priority[New priority]:priority:(${PRIORITIES.join(' ')})' \\
            '--title[New title]:title:' \\
            '--assignee[New assignee]:assignee:' \\
            $global_flags
          ;;
        completions)
          _arguments '1:shell:(bash zsh)'
          ;;
        *)
          _arguments $global_flags
          ;;
      esac
      ;;
  esac
}

_tasks
`;
}

/**
 * Build the `completions` Command, bound to the given root program so the
 * generated scripts reflect the exact set of registered subcommands.
 *
 * The factory shape (program -> Command) avoids a circular import: bin/tasks.ts
 * is the only place that constructs the root program, and it passes that
 * program in here when registering the completions subcommand.
 */
export function createCompletionsCommand(program: Command): Command {
  return new Command('completions')
    .description('Generate shell completion scripts')
    .argument('<shell>', 'Shell type: bash or zsh')
    .action((shell: string) => {
      switch (shell.toLowerCase()) {
        case 'bash':
          console.log(generateBashScript(program));
          break;
        case 'zsh':
          console.log(generateZshScript(program));
          break;
        default:
          console.error(`Unsupported shell: ${shell}. Use 'bash' or 'zsh'.`);
          process.exit(1);
      }
    });
}
